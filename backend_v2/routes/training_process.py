def _roles_of(text: str):
    """从 '商务经理 + 项目经理' 这类文本拆出角色列表。"""
    if not text:
        return []
    parts = []
    for chunk in text.replace("、", "+").replace("，", "+").replace(",", "+").replace("/", "+").split("+"):
        name = chunk.strip()
        if name:
            parts.append(name)
    return parts


def _match_roles(role_text: str):
    """把角色文本规整到 ALL_ROLES 里的标准角色(用于前端筛选)。"""
    raw = _roles_of(role_text)
    out = []
    for r in raw:
        hit = r if r in ALL_ROLES else None
        if hit is None:
            for std in ALL_ROLES:
                if r and (r in std or std in r):
                    hit = std
                    break
        if hit and hit not in out:
            out.append(hit)
    return out


@router.get("/process-flow")
def get_process_flow(
    project_type: str = Query("hardware", pattern="^(hardware|software)$"),
    _user=Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """返回从商务对接、合同签订到结题归档的完整流程节点。"""
    phases = (db.query(Phase)
              .filter(Phase.project_type == project_type)
              .order_by(Phase.sort_order, Phase.id).all())

    stages = []

    # ① 前置商务与立项
    stages.append({
        "key": "PRE",
        "seq": 0,
        "name": "商务对接与立项",
        "kind": "pre",
        "phase_code": None,
        "gate": None,
        "summary": "从客户对接到项目组成立——项目正式成立之前的必经动作",
        "entry": "客户有合作意向即可开始",
        "exit": "项目启动会召开后,正式进入 " + (phases[0].code if phases else "P0") + " 阶段",
        "nodes": PRE_NODES,
        "roles": sorted({r for n in PRE_NODES for r in n["roles"]},
                        key=lambda x: ALL_ROLES.index(x) if x in ALL_ROLES else 99),
        "deliverables": [],
    })

    # ② 项目阶段(读数据库真实配置)
    for idx, ph in enumerate(phases):
        gate = db.query(Gate).filter(Gate.phase_id == ph.id).first()
        stds = (db.query(GateDeliverableStandard)
                .filter(GateDeliverableStandard.phase_id == ph.id,
                        GateDeliverableStandard.is_active == True)
                .order_by(GateDeliverableStandard.sort_order, GateDeliverableStandard.id).all())

        deliverables = []
        role_set = []
        for s in stds:
            role_text = s.responsible_role or ROLE_FALLBACK.get(s.name, "")
            tpl = ""
            if s.template_path:
                # 模板文件名形如 gate_templates\std1_xxx_产品需求规格书_PRD.docx,取可读名
                base = s.template_path.replace("\\", "/").split("/")[-1]
                parts = base.split("_")
                tpl = "_".join(parts[2:]) if len(parts) > 2 else base
            deliverables.append({
                "name": s.name,
                "required": bool(s.required),
                "role": role_text,
                "template": tpl,
                "criteria": s.acceptance_criteria or "",
                "category": s.category or "other",
            })
            for r in _match_roles(role_text):
                if r not in role_set:
                    role_set.append(r)

        # 本阶段动作清单(数据库无对应表,以配置维护);未配置的阶段退回只展示交付物
        nodes = PHASE_NODES.get(ph.code, [])
        for n in nodes:
            for r in n["roles"]:
                if r in ALL_ROLES and r not in role_set:
                    role_set.append(r)

        entry, exit_ = PHASE_ENTRY_EXIT.get(ph.code, ("—", "—"))
        nxt = phases[idx + 1].code if idx + 1 < len(phases) else "结题归档"

        stages.append({
            "key": ph.code,
            "seq": idx + 1,
            "name": ph.name,
            "kind": "phase",
            "phase_code": ph.code,
            "gate": {"code": gate.code, "name": gate.name} if gate else None,
            "summary": ph.description or "",
            "entry": entry,
            "exit": exit_,
            "next": nxt,
            "roles": sorted(role_set, key=lambda x: ALL_ROLES.index(x) if x in ALL_ROLES else 99),
            "nodes": nodes,
            "deliverables": deliverables,
        })

    # ③ 收尾归档
    last_code = phases[-1].code if phases else "PP5"
    stages.append({
        "key": "POST",
        "seq": len(phases) + 1,
        "name": "结题与归档",
        "kind": "post",
        "phase_code": None,
        "gate": None,
        "summary": "从 " + last_code + " 收尾到项目正式结题——验收、回款、归档、沉淀",
        "entry": last_code + " 阶段工作完成",
        "exit": "管理层确认结题,项目关闭",
        "nodes": POST_NODES,
        "roles": sorted({r for n in POST_NODES for r in n["roles"]},
                        key=lambda x: ALL_ROLES.index(x) if x in ALL_ROLES else 99),
        "deliverables": [],
    })

    return {
        "project_type": project_type,
        "stages": stages,
        "roles": ALL_ROLES,
        "notes": FLOW_NOTES,
    }
